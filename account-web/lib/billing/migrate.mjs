import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { transaction } from "./transaction.mjs";

/** @typedef {{version: number, file: string, sha256: string, sql: string}} Migration */

/** Read only committed migrations with immutable, reviewed checksums.
 * @param {URL} [directory]
 * @returns {Promise<Migration[]>}
 */
export async function loadMigrations(directory = new URL("../../migrations/", import.meta.url)) {
  const manifest = JSON.parse(await readFile(new URL("manifest.json", directory), "utf8"));
  if (!Array.isArray(manifest) || !manifest.length) throw new Error("Invalid migration manifest");
  const migrations = [];
  for (let index = 0; index < manifest.length; index++) {
    const entry = manifest[index];
    if (entry.version !== index + 1 || !/^\d{4}_[a-z0-9_]+\.sql$/.test(entry.file) ||
        !/^[a-f0-9]{64}$/.test(entry.sha256)) {
      throw new Error("Invalid migration manifest");
    }
    const sql = await readFile(new URL(entry.file, directory), "utf8");
    const digest = createHash("sha256").update(sql).digest("hex");
    if (digest !== entry.sha256) throw new Error("Migration checksum does not match reviewed manifest");
    migrations.push({ ...entry, sql });
  }
  return migrations;
}

/** Explicit invocation only: never called by build, startup or a web request.
 * @param {import("./transaction.mjs").SqlPool} pool
 * @param {Migration[]} migrations
 */
export async function runMigrations(pool, migrations) {
  return transaction(pool, async (client) => {
    // Transaction lock works with direct and pooled connections; no session lock.
    await client.query("SELECT pg_advisory_xact_lock(1935763816, 1)");
    await client.query("CREATE SCHEMA IF NOT EXISTS saiph_billing");
    await client.query(`CREATE TABLE IF NOT EXISTS saiph_billing.schema_migrations (
      version integer PRIMARY KEY CHECK (version > 0),
      file text NOT NULL,
      sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
      applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
    )`);
    const { rows } = await client.query("SELECT version, file, sha256 FROM saiph_billing.schema_migrations ORDER BY version");
    for (const applied of rows) {
      const expected = migrations.find((migration) => migration.version === applied.version);
      if (!expected || expected.file !== applied.file || expected.sha256 !== applied.sha256) {
        throw new Error("Applied migration differs from reviewed history");
      }
    }
    const appliedVersions = new Set(rows.map((row) => row.version));
    const newlyApplied = [];
    for (const migration of migrations) {
      if (appliedVersions.has(migration.version)) continue;
      await client.query(migration.sql);
      await client.query(
        "INSERT INTO saiph_billing.schema_migrations (version,file,sha256) VALUES ($1,$2,$3)",
        [migration.version, migration.file, migration.sha256],
      );
      newlyApplied.push(migration.version);
    }
    return newlyApplied;
  });
}

/** Generate a secret-free, reviewed SQL-editor transaction from checked migrations.
 * @param {Migration[]} migrations
 */
export function exportMigrationSql(migrations) {
  if (!migrations.length || migrations.some((migration, index) =>
    migration.version !== index + 1 || !/^\d{4}_[a-z0-9_]+\.sql$/.test(migration.file) ||
    !/^[a-f0-9]{64}$/.test(migration.sha256) ||
    migration.sql.includes("$saiph_migration_"))) {
    throw new Error("Invalid migration export");
  }
  const known = migrations.map((migration) =>
    "(version=" + migration.version + " AND file='" + migration.file +
    "' AND sha256='" + migration.sha256 + "')",
  ).join(" OR ");
  const parts = [
    "-- Generated by npm run db:export. Review this entire transaction before running.",
    "-- Run only in the intended isolated account database SQL editor.",
    "-- Contains no connection string, owner subject, Stripe key or provider settings.",
    "BEGIN;",
    "SET LOCAL lock_timeout = '5s';",
    "SET LOCAL statement_timeout = '15s';",
    "SELECT pg_advisory_xact_lock(1935763816, 1);",
    "CREATE SCHEMA IF NOT EXISTS saiph_billing;",
    `CREATE TABLE IF NOT EXISTS saiph_billing.schema_migrations (
      version integer PRIMARY KEY CHECK (version > 0),
      file text NOT NULL,
      sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
      applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
    );`,
    "DO $saiph_history$",
    "BEGIN",
    "  IF EXISTS (SELECT 1 FROM saiph_billing.schema_migrations WHERE NOT (" + known + ")) THEN",
    "    RAISE EXCEPTION 'Applied migration differs from reviewed history';",
    "  END IF;",
    "END;",
    "$saiph_history$;",
  ];
  for (const migration of migrations) {
    const tag = "$saiph_migration_" + migration.version + "$";
    parts.push(
      "DO " + tag,
      "BEGIN",
      "  IF NOT EXISTS (SELECT 1 FROM saiph_billing.schema_migrations WHERE version=" + migration.version + ") THEN",
      migration.sql,
      "    INSERT INTO saiph_billing.schema_migrations (version,file,sha256) VALUES (" +
        migration.version + ",'" + migration.file + "','" + migration.sha256 + "');",
      "  END IF;",
      "END;",
      tag + ";",
    );
  }
  parts.push("COMMIT;", "");
  return parts.join("\n");
}
